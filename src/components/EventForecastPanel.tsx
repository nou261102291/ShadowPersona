import type { EventForecast } from '@/types/shadowpersona';

const money = new Intl.NumberFormat('en-US', {
  style: 'currency',
  currency: 'USD',
  maximumFractionDigits: 2,
});

const count = new Intl.NumberFormat('en-US', { maximumFractionDigits: 0 });

export default function EventForecastPanel({ forecast, label }: { forecast?: EventForecast; label: string }) {
  if (!forecast) {
    return (
      <section aria-label="Event financial forecast" className="rounded-2xl border border-violet-400/20 bg-[#101116] p-4 sm:p-5">
        <p className="text-[9px] font-semibold uppercase tracking-[0.18em] text-violet-300">Organizer planning model</p>
        <h2 className="mt-1 text-base font-semibold text-white">{label || 'Event forecast'}</h2>
        <p className="mt-2 text-[10px] leading-relaxed text-slate-400">
          Complete local reach, all three conversion assumptions, ticket and ancillary revenue, and each fixed and per-attendee cost
          to calculate a forecast. Entered figures are used directly; financial results are calculated by the app, not generated by AI.
        </p>
      </section>
    );
  }

  return (
    <section aria-label="Event financial forecast" className="space-y-4 rounded-2xl border border-violet-400/20 bg-[#101116] p-4 sm:p-5">
      <header className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <p className="text-[9px] font-semibold uppercase tracking-[0.18em] text-violet-300">Organizer planning model</p>
          <h2 className="mt-1 text-base font-semibold text-white">{label || 'Event forecast'}</h2>
        </div>
        <span className="rounded-full border border-amber-300/25 bg-amber-400/[0.08] px-2.5 py-1 text-[9px] font-semibold text-amber-100">
          {forecast.sampleAssumptions ? 'Sample assumptions' : 'Based on entered assumptions'}
        </span>
      </header>

      <p className="text-[10px] leading-relaxed text-slate-400">
        Attendance is calculated from aggregate local reach × the conversion range, capped at venue capacity when supplied.
        These are scenarios—not individual fan counts, guaranteed turnout, or audited financial advice.
      </p>

      <div className="overflow-x-auto rounded-lg border border-white/[0.07]">
        <table className="w-full min-w-[700px] border-collapse text-left text-[10px]">
          <thead className="bg-white/[0.03] text-slate-400">
            <tr>
              <th className="p-2.5 font-medium">Scenario</th>
              <th className="p-2.5 text-right font-medium">Attendance</th>
              <th className="p-2.5 text-right font-medium">Revenue</th>
              <th className="p-2.5 text-right font-medium">Costs</th>
              <th className="p-2.5 text-right font-medium">Operating result</th>
              <th className="p-2.5 text-right font-medium">Margin</th>
            </tr>
          </thead>
          <tbody>
            {forecast.scenarios.map((scenario) => (
              <tr className="border-t border-white/[0.06]" key={scenario.label}>
                <th className="p-2.5 font-semibold text-slate-200">{scenario.label}</th>
                <td className="p-2.5 text-right tabular-nums text-slate-300">{count.format(scenario.attendance)}</td>
                <td className="p-2.5 text-right tabular-nums text-slate-300">{money.format(scenario.totalRevenueUsd)}</td>
                <td className="p-2.5 text-right tabular-nums text-slate-300">{money.format(scenario.totalCostsUsd)}</td>
                <td
                  className={`p-2.5 text-right font-semibold tabular-nums ${
                    scenario.operatingProfitUsd >= 0 ? 'text-lime-300' : 'text-rose-300'
                  }`}
                >
                  {money.format(scenario.operatingProfitUsd)}
                </td>
                <td className="p-2.5 text-right tabular-nums text-slate-300">
                  {scenario.operatingMarginPct === null ? '—' : `${scenario.operatingMarginPct.toFixed(1)}%`}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      <div className="grid gap-2 sm:grid-cols-2">
        <div className="rounded-lg border border-white/[0.07] bg-white/[0.02] p-3">
          <p className="text-[9px] uppercase tracking-wider text-slate-500">Break-even attendance</p>
          <p className="mt-1 text-lg font-semibold text-white">
            {forecast.breakEvenAttendance === null ? 'Not calculable' : count.format(forecast.breakEvenAttendance)}
          </p>
          <p className="mt-1 text-[9px] text-slate-500">
            Based on expected blended ticket price, fees, sponsor and merchandise assumptions.
          </p>
        </div>
        <div className="rounded-lg border border-white/[0.07] bg-white/[0.02] p-3">
          <p className="text-[9px] uppercase tracking-wider text-slate-500">Venue-capacity check</p>
          <p className="mt-1 text-lg font-semibold text-white">
            {forecast.venueCapacity === null ? 'Capacity not supplied' : count.format(forecast.venueCapacity)}
          </p>
          <p className="mt-1 text-[9px] text-slate-500">
            {forecast.breakEvenWithinCapacity === null
              ? 'Add capacity and complete cost assumptions to assess feasibility.'
              : forecast.breakEvenWithinCapacity
                ? 'Break-even attendance is within the entered capacity.'
                : 'Break-even attendance exceeds the entered venue capacity.'}
          </p>
        </div>
      </div>

      <details className="text-[9px] text-slate-500">
        <summary className="cursor-pointer text-slate-400">Show calculation breakdown</summary>
        <div className="mt-2 grid gap-1 sm:grid-cols-3">
          {forecast.scenarios.map((scenario) => (
            <p key={`${scenario.label}-breakdown`}>
              {scenario.label}: tickets {money.format(scenario.ticketRevenueUsd)} + sponsorship {money.format(scenario.sponsorshipRevenueUsd)} +
              merchandise {money.format(scenario.merchandiseRevenueUsd)}; fixed costs {money.format(scenario.fixedCostsUsd)}, variable costs{' '}
              {money.format(scenario.variableCostsUsd)}, fees {money.format(scenario.ticketingFeesUsd)}.
            </p>
          ))}
        </div>
      </details>
    </section>
  );
}
